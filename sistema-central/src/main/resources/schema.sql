CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(80) NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS sessoes (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuarios(id),
    identificador UUID NOT NULL UNIQUE,
    token INTEGER NOT NULL CHECK (token BETWEEN 0 AND 100),
    expira_em TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS filmes (
    id TEXT PRIMARY KEY,
    nome TEXT NOT NULL,
    genero TEXT NOT NULL,
    foto TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS diretores (
    id TEXT PRIMARY KEY,
    nome TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS votos (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuarios(id),
    filme_id TEXT NOT NULL REFERENCES filmes(id),
    filme_nome TEXT NOT NULL,
    diretor_id TEXT NOT NULL REFERENCES diretores(id),
    diretor_nome TEXT NOT NULL,
    confirmado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
